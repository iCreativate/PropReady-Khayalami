import type { IqProperty } from './types';

function series(
    startValue: number,
    endValue: number,
    startEquity: number,
    endEquity: number,
    rental: number,
    months: number
): IqProperty['history'] {
    const out: IqProperty['history'] = [];
    const now = new Date();
    for (let i = months - 1; i >= 0; i--) {
        const t = 1 - i / Math.max(1, months - 1);
        const d = new Date(now);
        d.setMonth(d.getMonth() - i);
        const value = Math.round(startValue + (endValue - startValue) * t);
        const equity = Math.round(startEquity + (endEquity - startEquity) * t);
        const cashFlow = Math.round(rental * 0.35 + (Math.sin(i / 3) * 400));
        const growth = t > 0.05 ? ((value - startValue) / startValue) * 100 : 0;
        out.push({
            month: d.toLocaleDateString('en-ZA', { month: 'short', year: '2-digit' }),
            value,
            equity,
            rental,
            cashFlow,
            growth: Math.round(growth * 10) / 10,
        });
    }
    return out;
}


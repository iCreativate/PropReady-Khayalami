export function getConveyancerBySlug(slug: string): ConveyancerProfile | undefined {
    return CONVEYANCERS.find((c) => c.slug === slug);
}

export function getConveyancerById(id: string): ConveyancerProfile | undefined {
    return CONVEYANCERS.find((c) => c.id === id);
}

export function getFeaturedConveyancers(): ConveyancerProfile[] {
    return CONVEYANCERS.filter((c) => c.featured);
}

export function listProvinces(): ProvinceSlug[] {
    return Array.from(new Set(CONVEYANCERS.map((c) => c.province)));
}

export function listCities(province?: ProvinceSlug | ''): string[] {
    const rows = province ? CONVEYANCERS.filter((c) => c.province === province) : CONVEYANCERS;
    return Array.from(new Set(rows.map((c) => c.city))).sort();
}

export function listSuburbs(province?: ProvinceSlug | '', city?: string): string[] {
    let rows = CONVEYANCERS;
    if (province) rows = rows.filter((c) => c.province === province);
    if (city) rows = rows.filter((c) => c.city.toLowerCase() === city.toLowerCase());
    return Array.from(new Set(rows.map((c) => c.suburb))).sort();
}

export function cityToSlug(city: string): string {
    return city
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');
}

export function findCityBySlug(province: ProvinceSlug, citySlug: string): string | undefined {
    return listCities(province).find((c) => cityToSlug(c) === citySlug);
}


function review(
    id: string,
    author: string,
    role: ConveyancerProfile['reviews'][0]['role'],
    rating: number,
    title: string,
    body: string,
    date: string,
    helpful: number,
    response?: string
): ConveyancerProfile['reviews'][0] {
    const base = Math.max(3.5, rating - 0.2);
    return {
        id,
        author,
        role,
        rating,
        axes: {
            communication: base + 0.1,
            professionalism: rating,
            transparency: base,
            value: base - 0.1,
            speed: base,
            knowledge: rating,
            overall: rating,
        },
        title,
        body,
        date,
        verified: true,
        helpful,
        response,
    };
}

